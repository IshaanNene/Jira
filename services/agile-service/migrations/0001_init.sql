-- Agile service: boards, sprints, and where each issue sits (rank and sprint).
-- All tenant-owned. Issues themselves live in issue-service and are referenced by id.

CREATE FUNCTION app_tenant_id() RETURNS uuid
    LANGUAGE sql STABLE PARALLEL SAFE
    AS $$ SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid $$;

CREATE TABLE boards (
    id          uuid PRIMARY KEY,
    tenant_id   uuid NOT NULL,
    project_id  uuid NOT NULL,
    -- Denormalised (project keys are immutable) for display and default sprint names.
    project_key text NOT NULL,
    name        text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    kind        text NOT NULL CHECK (kind IN ('scrum', 'kanban')),
    -- [{ "id", "name", "statuses": [status keys], "category": todo|in_progress|done|null, "wip_limit" }]
    columns     jsonb NOT NULL,
    version     bigint NOT NULL DEFAULT 1,
    created_by  uuid NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    deleted_at  timestamptz
);
CREATE UNIQUE INDEX boards_name_idx ON boards (tenant_id, project_id, lower(name)) WHERE deleted_at IS NULL;

CREATE TABLE sprints (
    id           uuid PRIMARY KEY,
    tenant_id    uuid NOT NULL,
    board_id     uuid NOT NULL REFERENCES boards (id),
    project_id   uuid NOT NULL,
    sequence     integer NOT NULL,
    name         text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    goal         text NOT NULL DEFAULT '' CHECK (char_length(goal) <= 500),
    state        text NOT NULL DEFAULT 'future' CHECK (state IN ('future', 'active', 'closed')),
    -- Planned dates.
    start_date   date,
    end_date     date,
    -- What actually happened.
    started_at   timestamptz,
    completed_at timestamptz,
    -- Snapshot when the sprint started: { "issues": n, "points": x }.
    commitment   jsonb,
    -- Frozen outcome when the sprint was completed (completed / incomplete issues, burndown).
    report       jsonb,
    version      bigint NOT NULL DEFAULT 1,
    created_by   uuid NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, board_id, sequence)
);
-- A board runs one sprint at a time.
CREATE UNIQUE INDEX sprints_one_active_idx ON sprints (tenant_id, board_id) WHERE state = 'active';

-- One row per issue that has ever appeared on a board: its order within the project
-- (shared by every board of that project) and the sprint it is planned into.
CREATE TABLE issue_placements (
    tenant_id  uuid NOT NULL,
    issue_id   uuid NOT NULL,
    project_id uuid NOT NULL,
    -- Fractional rank; byte order is the board order. Only ever generated by the server.
    rank       text COLLATE "C" NOT NULL,
    sprint_id  uuid REFERENCES sprints (id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, issue_id)
);
CREATE INDEX issue_placements_rank_idx ON issue_placements (tenant_id, project_id, rank);
CREATE INDEX issue_placements_sprint_idx ON issue_placements (tenant_id, sprint_id) WHERE sprint_id IS NOT NULL;

-- Append-only: when issues entered or left a sprint. Burndown scope is derived from it.
CREATE TABLE sprint_scope_events (
    id        uuid PRIMARY KEY,
    tenant_id uuid NOT NULL,
    sprint_id uuid NOT NULL REFERENCES sprints (id) ON DELETE CASCADE,
    issue_id  uuid NOT NULL,
    action    text NOT NULL CHECK (action IN ('added', 'removed')),
    actor_id  uuid NOT NULL,
    at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sprint_scope_events_idx ON sprint_scope_events (tenant_id, sprint_id, at);

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['boards', 'sprints', 'issue_placements', 'sprint_scope_events'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON %I USING (tenant_id = app_tenant_id()) WITH CHECK (tenant_id = app_tenant_id())', t);
    END LOOP;
END $$;

CREATE TABLE outbox (
    id            uuid PRIMARY KEY,
    tenant_id     uuid,
    topic         text NOT NULL,
    partition_key text NOT NULL,
    event_type    text NOT NULL,
    payload       jsonb NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    published_at  timestamptz,
    attempts      integer NOT NULL DEFAULT 0,
    last_error    text
);
CREATE INDEX outbox_unpublished_idx ON outbox (created_at) WHERE published_at IS NULL;

CREATE TABLE inbox (
    consumer     text NOT NULL,
    event_id     uuid NOT NULL,
    processed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (consumer, event_id)
);
